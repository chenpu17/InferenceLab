/**
 * The UI is Chinese-first. English copy is keyed by the Chinese source string
 * so the Chinese UI stays byte-for-byte unchanged and translators can work
 * without inventing a second key namespace.
 */
export const en: Record<string, string> = {
  ...common,
  ...header,
  ...config,
  ...canvas,
  ...inspector,
  ...lenses,
  ...reference,
  ...experiments,
  ...presets,
  ...domain,
  ...store,
  ...onboarding,
};

/**
 * Chinese overrides for English domain tokens (status enums, engine roles).
 * Chinese UI copy is written directly as the source string, so this map only
 * contains values that must remain English in code.
 */
export const zh: Record<string, string> = {
  ...zhDomain,
};

export function interpolate(template: string, params?: MessageParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] === undefined ? match : String(params[name]),
  );
}

export function translate(source: string, locale: Locale, params?: MessageParams): string {
  const template = locale === 'en' ? (en[source] ?? source) : (zh[source] ?? source);
  return interpolate(template, params);
}

type TemplateMatcher = {
  regex: RegExp;
  template: string;
  names: string[];
  specificity: number;
};

let matchers: TemplateMatcher[] | null = null;

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function buildMatchers(): TemplateMatcher[] {
  const built: TemplateMatcher[] = [];
  for (const [source, target] of Object.entries(en)) {
    if (!source.includes('{')) continue;
    const names: string[] = [];
    let pattern = '^';
    let lastIndex = 0;
    const placeholder = /\{(\w+)\}/g;
    let match: RegExpExecArray | null;
    while ((match = placeholder.exec(source)) !== null) {
      pattern += escapeRegExp(source.slice(lastIndex, match.index));
      pattern += '(.+?)';
      names.push(match[1]!);
      lastIndex = match.index + match[0].length;
    }
    pattern += escapeRegExp(source.slice(lastIndex)) + '$';
    built.push({
      regex: new RegExp(pattern),
      template: target,
      names,
      specificity: source.replace(/\{\w+\}/g, '').length,
    });
  }
  // Prefer the template with the most literal text when several could match.
  return built.sort((a, b) => b.specificity - a.specificity);
}

/**
 * Localizes a domain string that was generated by core/profiles. Exact copy is
 * preferred; otherwise placeholder templates are matched so messages such as
 * "Rank r0 的 KV 池不足以容纳一个 Block" can be translated without changing
 * the engine's message format.
 */
export function localize(text: string | null | undefined, locale: Locale): string {
  if (text === null || text === undefined || text === '') return '';
  if (locale === 'zh') return zh[text] ?? text;
  const exact = en[text];
  if (exact !== undefined) return exact;
  matchers ??= buildMatchers();
  for (const matcher of matchers) {
    const match = text.match(matcher.regex);
    if (!match) continue;
    const params: MessageParams = {};
    matcher.names.forEach((name, index) => {
      params[name] = match[index + 1] ?? '';
    });
    return interpolate(matcher.template, params);
  }
  return text;
}

/** Test/debug helper: whether a Chinese source string has English copy. */
export function hasEnglish(source: string): boolean {
  return en[source] !== undefined;
}
